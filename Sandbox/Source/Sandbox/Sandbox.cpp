// OPAAX_LOG expands to an unqualified ToSpdLevel(...) — bring Opaax into scope, as engine TUs do.
using namespace Opaax;

namespace
{
    constexpr LogCategory LogSandboxModule{"SandboxModule"};
}

void SandboxModule::OnRegister(Opaax::ModuleRegistrar& InRegistrar)
{
    // A component the GAME owns — the engine has never heard of HealthComponent, yet it
    // round-trips through capture/instantiate like any native type. That is the whole point
    // of the route: satisfying CComponent is the entire contract.
    //
    // NOTE: DummyComponent is deliberately NOT registered here any more. It is an engine
    // type, and the engine registers its own natives first (MR2) — asking again would be
    // refused as a duplicate.
    InRegistrar.Components().Register<Sandbox::HealthComponent>();

    // The first caller of OpaaxTag (I14). Nothing new is needed to make it serializable: an
    // OpaaxTagContainer writes as an array of strings, so a tag is readable in the .opaaxmap.
    InRegistrar.Components().Register<Sandbox::TagsComponent>();

    // A world subsystem the ENGINE has never heard of. Play-only: it exists in a Play world and is
    // never constructed in an Edit one (WS1/WS2). Registering costs one line — no base-class
    // ceremony, no reflection, no static-init.
    //
    // NOTE: this is the only world-subsystem candidate in either host now. The Edit-only
    // QuadBoundsSubsystem that used to make SandboxEditor.exe's count two was deleted on
    // 2026-08-31 — see SandboxEditorModule.cpp for what that costs.
    //InRegistrar.WorldSubsystems().Register<Sandbox::QuadOscillatorSubsystem>();

    // ⑦-A P5b — the game's side of the mover seam: keys in, MoverInput out. It is also what
    // puts a caller back on this route, which has had none in either host since the line above
    // was commented out.
    InRegistrar.WorldSubsystems().Register<Sandbox::PlayerControlSubsystem>();

    // A resource type the ENGINE has never heard of, claiming its own extension. This is what makes
    // `.wave` a known file everywhere at once — the browser names it, and the editor module adds
    // only an icon. Registering it here rather than editor-side is deliberate: a wave is game
    // CONTENT, so Sandbox.exe must know it too.
    InRegistrar.Resources().Register<Sandbox::WaveResource>();

    OPAAX_LOG(LogSandboxModule, Info,
        "RegisterModule: components={}, worldSubsystems={}, resourceFormats={}",
        InRegistrar.Components().Count(), InRegistrar.WorldSubsystems().Count(),
        InRegistrar.Resources().Count());
}

